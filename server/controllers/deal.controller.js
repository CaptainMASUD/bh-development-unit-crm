/* =======================
   MARK DEAL LOST
======================= */
export const markDealLost = async (req, res) => {
  try {
    const meta = getReqMeta(req);

    const id = toObjectId(req.params.id);
    if (!id) return res.status(400).json({ message: "Invalid deal id" });

    const before = await Deal.findById(id).lean();
    if (!before) return res.status(404).json({ message: "Deal not found" });

    if (before.leadId) {
      await assertLeadAccessOrThrow({ req, leadId: before.leadId });
    }

    const { reason = "" } = req.body || {};

    if (!normalizeString(reason)) {
      return res.status(400).json({ message: "reason is required" });
    }

    const deal = await Deal.findByIdAndUpdate(
      id,
      {
        $set: {
          stage: "lost",
          probability: 0,
          expectedRevenue: 0,
          lostAt: new Date(),
          lostReason: normalizeString(reason),
          dealHealth: "critical",
          stuckReason: normalizeString(reason),
          nextDealAction: "Review lost deal",
          nextDealActionAt: null,
          lastStageChangedAt: new Date(),
          lastActivityAt: new Date(),
        },
      },
      { new: true, runValidators: true }
    );

    let updatedLead = null;

    if (deal.leadId) {
      updatedLead = await syncLeadForDeal({
        leadId: deal.leadId,
        deal,
        action: "lost",
        userId: req.user._id,
      });
    }

    await WorkQueue.updateMany(
      { dealId: deal._id, status: { $in: ["pending", "in_progress", "snoozed"] } },
      { $set: { status: "cancelled", result: "Deal lost" } }
    );

    await writeAudit({
      actorId: req.user._id,
      action: "lost",
      entityType: "Deal",
      entityId: deal._id,
      before,
      after: deal.toObject(),
      meta,
    });

    await writeActivity({
      leadId: deal.leadId,
      customerId: deal.customerId,
      dealId: deal._id,
      proposalId: deal.proposalId,
      entityType: "Deal",
      entityId: deal._id,
      type: "deal_lost",
      message: "Deal lost",
      createdBy: req.user._id,
      meta: {
        amount: deal.grandTotal,
        reason,
      },
    });

    return res.json({
      message: "Deal marked as lost",
      deal,
      lead: updatedLead,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to mark deal lost",
      error: err.message,
    });
  }
};

/* =======================
   DELETE DEAL
======================= */
export const deleteDeal = async (req, res) => {
  try {
    const meta = getReqMeta(req);

    const id = toObjectId(req.params.id);
    if (!id) return res.status(400).json({ message: "Invalid deal id" });

    const before = await Deal.findById(id).lean();
    if (!before) return res.status(404).json({ message: "Deal not found" });

    if (before.leadId) {
      await assertLeadAccessOrThrow({ req, leadId: before.leadId });
    }

    if (!isAdminOrSuperAdmin(req) && String(before.createdBy) !== String(req.user._id)) {
      return res.status(403).json({
        message: "Only creator or admin can delete this deal.",
      });
    }

    await Deal.findByIdAndDelete(id);

    await WorkQueue.updateMany(
      { dealId: id, status: { $in: ["pending", "in_progress", "snoozed"] } },
      { $set: { status: "cancelled", result: "Deal deleted" } }
    );

    if (before.proposalId) {
      await Proposal.findByIdAndUpdate(before.proposalId, {
        $set: { dealId: null },
      });
    }

    await writeAudit({
      actorId: req.user._id,
      action: "delete",
      entityType: "Deal",
      entityId: id,
      before,
      after: null,
      meta,
    });

    await writeActivity({
      leadId: before.leadId,
      customerId: before.customerId,
      dealId: id,
      proposalId: before.proposalId,
      entityType: "Deal",
      entityId: id,
      type: "deleted",
      message: "Deal deleted",
      createdBy: req.user._id,
    });

    return res.json({
      message: "Deal deleted",
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to delete deal",
      error: err.message,
    });
  }
};