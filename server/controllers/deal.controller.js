const toObjectId = (v) => {
  if (!v) return null;
  return mongoose.Types.ObjectId.isValid(v)
    ? new mongoose.Types.ObjectId(v)
    : null;
};

const normalizeString = (value = "") => String(value || "").trim();

const validateDateOrNull = (value) => {
  if (!value) return null;
  const dt = new Date(value);
  if (Number.isNaN(dt.getTime())) return null;
  return dt;
};

const isAdminOrSuperAdmin = (req) => {
  const role = req?.user?.role;
  return role === "admin" || role === "superadmin";
};

const assertLeadAccessOrThrow = async ({ req, leadId }) => {
  if (!leadId) return true;
  if (isAdminOrSuperAdmin(req)) return true;

  const me = new mongoose.Types.ObjectId(req.user._id);

  const exists = await Lead.exists({
    _id: leadId,
    $or: [
      { assignedTo: me },
      { allowedUsers: me },
      { createdBy: me, ownerLocked: false },
    ],
  });

  if (!exists) {
    const err = new Error("Not authorized to access this lead");
    err.statusCode = 403;
    throw err;
  }

  return true;
};

const DEAL_STAGES = ["new", "qualified", "proposal", "negotiation", "won", "lost"];

const PROPOSAL_STATUSES = ["none", "draft", "sent", "accepted", "rejected", "expired"];

const calculateItems = (items = []) => {
  let subtotal = 0;
  let discountTotal = 0;

  const normalized = Array.isArray(items)
    ? items.map((item) => {
        const qty = Math.max(Number(item.qty || 0), 0);
        const unitPrice = Math.max(Number(item.unitPrice || 0), 0);
        const discount = Math.max(Number(item.discount || 0), 0);

        const rawTotal = qty * unitPrice;
        const lineTotal = Math.max(rawTotal - discount, 0);

        subtotal += rawTotal;
        discountTotal += discount;

        return {
          productId: toObjectId(item.productId),
          nameSnapshot: normalizeString(item.nameSnapshot),
          qty,
          unitPrice,
          discount,
          lineTotal,
        };
      })
    : [];

  return {
    items: normalized,
    subtotal,
    discountTotal,
    grandTotal: Math.max(subtotal - discountTotal, 0),
  };
};

const getExpectedRevenue = (grandTotal, probability) => {
  return Math.round(Number(grandTotal || 0) * (Number(probability || 0) / 100));
};

const getDealHealth = ({ stage, expectedCloseDate, lastActivityAt, probability }) => {
  if (stage === "won") return "healthy";
  if (stage === "lost") return "critical";

  const now = new Date();
  const closeDate = validateDateOrNull(expectedCloseDate);

  if (closeDate && closeDate < now) return "critical";

  if (!lastActivityAt) return "at_risk";

  const last = new Date(lastActivityAt);
  const daysSilent = Math.floor((now - last) / (24 * 60 * 60 * 1000));

  if (daysSilent >= 7) return "stuck";
  if (daysSilent >= 3) return "at_risk";

  if (Number(probability || 0) >= 70) return "healthy";

  return "unknown";
};

const getStartOfDay = (date = new Date()) => {
  const d = new Date(date);
  d.setHours(0, 0, 0, 0);
  return d;
};

const createOrUpdateDealQueue = async ({
  deal,
  lead = null,
  source = "manual",
  title = "Review deal",
  description = "",
  recommendedAction = "review",
  dueAt = null,
  priority = "normal",
  priorityScore = 70,
  createdBy,
}) => {
  try {
    const assignedTo = deal?.ownerId || lead?.assignedTo || deal?.createdBy;
    if (!deal?._id || !assignedTo) return null;

    return await WorkQueue.findOneAndUpdate(
      {
        dealId: deal._id,
        assignedTo,
        source,
        status: { $in: ["pending", "in_progress", "snoozed"] },
      },
      {
        $set: {
          queueDate: getStartOfDay(dueAt || new Date()),
          leadId: deal.leadId || null,
          customerId: deal.customerId || lead?.customerId || null,
          proposalId: deal.proposalId || null,
          title,
          description,
          recommendedAction,
          priority,
          priorityScore,
          dueAt,
          createdBy,
          autoGenerated: true,
        },
        $setOnInsert: {
          dealId: deal._id,
          assignedTo,
          status: "pending",
        },
      },
      { new: true, upsert: true, runValidators: true }
    );
  } catch (err) {
    console.error("Deal work queue failed:", err.message);
    return null;
  }
};

const createNotificationSafe = async ({
  userId,
  title,
  message,
  type = "deal",
  priority = "normal",
  entityType = "Deal",
  entityId,
  createdBy,
}) => {
  try {
    if (!userId || !title) return null;

    return await Notification.create({
      userId,
      title,
      message,
      type,
      priority,
      entityType,
      entityId,
      createdBy,
    });
  } catch (err) {
    console.error("Notification failed:", err.message);
    return null;
  }
};

const syncLeadForDeal = async ({ leadId, deal, action, userId }) => {
  if (!leadId) return null;

  const lead = await Lead.findById(leadId);
  if (!lead) return null;

  const set = {
    lastActivityAt: new Date(),
    untouchedSinceCreated: false,
  };

  let note = "Deal updated";
  let reason = "Deal updated";

  if (action === "created") {
    set.pipelineStage =
      deal.stage === "proposal"
        ? "proposal"
        : deal.stage === "negotiation"
        ? "negotiation"
        : "qualified";

    set.nextAction = "Work on this deal";
    set.nextActionType = "deal";
    set.nextActionAt = deal.nextDealActionAt || deal.expectedCloseDate || null;
    set.workQueuePriority = "high";
    set.workQueueScore = Math.max(Number(lead.workQueueScore || 0), 95);

    note = `Deal created: ${deal.title}`;
    reason = "Deal created";
  }

  if (action === "won") {
    set.pipelineStage = "won";
    set.status = "confirmed";
    set.wonReason = deal.wonReason || "Deal won";
    set.wonAt = deal.wonAt || new Date();
    set.isOverdue = false;
    set.overdueSince = null;
    set.nextAction = "Convert won lead to customer";
    set.nextActionType = "convert";
    set.nextActionAt = null;
    set.workQueuePriority = "high";
    set.workQueueScore = 120;

    note = `Deal won: ${deal.title}`;
    reason = deal.wonReason || "Deal won";
  }

  if (action === "lost") {
    set.pipelineStage = "lost";
    set.status = "lost";
    set.lostReason = deal.lostReason || "Deal lost";
    set.lostAt = deal.lostAt || new Date();
    set.isOverdue = false;
    set.overdueSince = null;
    set.nextAction = "Review lost deal reason";
    set.nextActionType = "lost_review";
    set.nextActionAt = null;
    set.workQueuePriority = "low";
    set.workQueueScore = 0;

    note = `Deal lost: ${deal.title}`;
    reason = deal.lostReason || "Deal lost";
  }

  return await Lead.findByIdAndUpdate(
    leadId,
    {
      $set: set,
      $push: {
        notes: {
          note,
          type:
            action === "won"
              ? "won_reason"
              : action === "lost"
              ? "lost_reason"
              : "stage_change",
          oldStage: lead.pipelineStage || "",
          newStage: set.pipelineStage || lead.pipelineStage || "",
          oldStatus: lead.status || "",
          newStatus: set.status || lead.status || "",
          reason,
          createdBy: userId,
          createdAt: new Date(),
        },
      },
    },
    { new: true, runValidators: true }
  );
};

/* =======================
   CREATE DEAL
======================= */
export const createDeal = async (req, res) => {
  try {
    const meta = getReqMeta(req);

    const {
      leadId,
      customerId = null,
      proposalId = null,
      title,
      stage = "new",
      currency = "BDT",
      items = [],
      probability = 10,
      expectedCloseDate = null,
      proposalStatus = "none",
      proposalSentAt = null,
      quotationValidTill = null,
      requirementSnapshot = {},
      ownerId = null,
      notes = "",
      nextDealAction = "",
      nextDealActionAt = null,
      stuckReason = "",
    } = req.body || {};

    const safeLeadId = toObjectId(leadId);
    let safeCustomerId = toObjectId(customerId);
    const safeProposalId = toObjectId(proposalId);

    let sourceLead = null;

    if (safeLeadId) {
      await assertLeadAccessOrThrow({ req, leadId: safeLeadId });
      sourceLead = await Lead.findById(safeLeadId).lean();

      if (!safeCustomerId && sourceLead?.customerId) {
        safeCustomerId = toObjectId(sourceLead.customerId);
      }
    }

    if (!safeCustomerId) {
      return res.status(400).json({
        message: "Deal requires customerId. Convert lead to customer first or provide customerId.",
      });
    }

    if (!title || !normalizeString(title)) {
      return res.status(400).json({ message: "title is required" });
    }

    if (!DEAL_STAGES.includes(stage)) {
      return res.status(400).json({
        message: `Invalid stage. Use: ${DEAL_STAGES.join(", ")}`,
      });
    }

    if (!PROPOSAL_STATUSES.includes(proposalStatus)) {
      return res.status(400).json({
        message: `Invalid proposalStatus. Use: ${PROPOSAL_STATUSES.join(", ")}`,
      });
    }

    const totals = calculateItems(items);
    const safeProbability = Math.min(Math.max(Number(probability || 10), 0), 100);
    const safeExpectedCloseDate = validateDateOrNull(expectedCloseDate);
    const safeNextDealActionAt = validateDateOrNull(nextDealActionAt);
    const grandTotal = totals.grandTotal;

    const health = getDealHealth({
      stage,
      expectedCloseDate: safeExpectedCloseDate,
      lastActivityAt: new Date(),
      probability: safeProbability,
    });

    const deal = await Deal.create({
      leadId: safeLeadId,
      customerId: safeCustomerId,
      proposalId: safeProposalId,
      title: normalizeString(title),
      stage,
      currency: normalizeString(currency) || "BDT",
      items: totals.items,
      subtotal: totals.subtotal,
      discountTotal: totals.discountTotal,
      grandTotal,
      expectedRevenue: getExpectedRevenue(grandTotal, safeProbability),
      probability: safeProbability,
      expectedCloseDate: safeExpectedCloseDate,
      proposalStatus,
      proposalSentAt: validateDateOrNull(proposalSentAt),
      quotationValidTill: validateDateOrNull(quotationValidTill),
      requirementSnapshot: {
        summary: normalizeString(requirementSnapshot?.summary),
        budgetMin: Math.max(Number(requirementSnapshot?.budgetMin || 0), 0),
        budgetMax: Math.max(Number(requirementSnapshot?.budgetMax || 0), 0),
        expectedValue: Math.max(Number(requirementSnapshot?.expectedValue || 0), 0),
        timeline: normalizeString(requirementSnapshot?.timeline),
        decisionMaker: normalizeString(requirementSnapshot?.decisionMaker),
      },
      ownerId: toObjectId(ownerId) || req.user._id,
      createdBy: req.user._id,
      notes: normalizeString(notes),

      dealHealth: health,
      nextDealAction: normalizeString(nextDealAction) || "Work on this deal",
      nextDealActionAt: safeNextDealActionAt || safeExpectedCloseDate,
      stuckReason: normalizeString(stuckReason),
      lastActivityAt: new Date(),
      lastStageChangedAt: new Date(),
    });

    let updatedLead = null;

    if (safeLeadId) {
      updatedLead = await syncLeadForDeal({
        leadId: safeLeadId,
        deal,
        action: "created",
        userId: req.user._id,
      });

      await writeActivity({
        leadId: safeLeadId,
        customerId: safeCustomerId,
        dealId: deal._id,
        proposalId: safeProposalId,
        entityType: "Deal",
        entityId: deal._id,
        type: "deal_created",
        message: "Deal created",
        createdBy: req.user._id,
        meta: {
          dealId: deal._id,
          amount: deal.grandTotal,
          stage: deal.stage,
        },
      });
    }

    if (safeProposalId) {
      await Proposal.findByIdAndUpdate(safeProposalId, {
        $set: { dealId: deal._id },
      });
    }

    await createOrUpdateDealQueue({
      deal,
      lead: updatedLead,
      source: "manual",
      title: deal.nextDealAction || "Work on deal",
      description: deal.title,
      recommendedAction: "review",
      priority: deal.dealHealth === "critical" ? "urgent" : "high",
      priorityScore: deal.dealHealth === "critical" ? 130 : 90,
      dueAt: deal.nextDealActionAt || deal.expectedCloseDate || new Date(),
      createdBy: req.user._id,
    });

    await createNotificationSafe({
      userId: deal.ownerId,
      title: "New deal created",
      message: deal.title,
      priority: deal.dealHealth === "critical" ? "urgent" : "high",
      entityId: deal._id,
      createdBy: req.user._id,
    });

    await writeAudit({
      actorId: req.user._id,
      action: "create",
      entityType: "Deal",
      entityId: deal._id,
      before: null,
      after: deal.toObject(),
      meta,
    });

    return res.status(201).json({
      message: "Deal created",
      deal,
      lead: updatedLead,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to create deal",
      error: err.message,
    });
  }
};

/* =======================
   LIST DEALS
======================= */
export const listDeals = async (req, res) => {
  try {
    const {
      leadId,
      customerId,
      stage,
      ownerId,
      dealHealth,
      q,
      limit = 50,
    } = req.query || {};

    const filter = {};

    const safeLeadId = toObjectId(leadId);
    if (safeLeadId) {
      await assertLeadAccessOrThrow({ req, leadId: safeLeadId });
      filter.leadId = safeLeadId;
    }

    const safeCustomerId = toObjectId(customerId);
    if (safeCustomerId) filter.customerId = safeCustomerId;

    const safeOwnerId = toObjectId(ownerId);
    if (safeOwnerId) filter.ownerId = safeOwnerId;

    if (stage && DEAL_STAGES.includes(String(stage))) filter.stage = stage;
    if (dealHealth) filter.dealHealth = dealHealth;

    const pageSize = Math.min(Math.max(parseInt(limit || "50", 10), 1), 100);

    let query = Deal.find(filter)
      .populate("createdBy", "name email role avatarUrl")
      .populate("ownerId", "name email role avatarUrl");

    if (q && normalizeString(q)) {
      query = query
        .find({ ...filter, $text: { $search: normalizeString(q) } })
        .select({ score: { $meta: "textScore" } })
        .sort({ score: { $meta: "textScore" }, _id: -1 });
    } else {
      query = query.sort({ createdAt: -1 });
    }

    const items = await query.limit(pageSize).lean();

    return res.json({ items });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to list deals",
      error: err.message,
    });
  }
};

