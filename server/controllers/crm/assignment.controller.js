import mongoose from "mongoose";
import User from "../../models/user.model.js";
import Lead from "../../models/lead.model.js";
import LeadAssignmentRule from "../../models/leadAssignmentRule.model.js";
import WorkQueue from "../../models/workQueue.model.js";
import Notification from "../../models/notification.model.js";
import { getReqMeta, writeAudit, writeActivity } from "../../utils/audit.js";

const toObjectId = (v) => {
  if (!v) return null;
  return mongoose.Types.ObjectId.isValid(v)
    ? new mongoose.Types.ObjectId(v)
    : null;
};

const normalizeString = (value = "") => String(value || "").trim();

const normalizeLower = (value = "") => normalizeString(value).toLowerCase();

const isAdminOrSuperAdmin = (req) => {
  const role = req?.user?.role;
  return role === "admin" || role === "superadmin";
};

const assertAdmin = (req) => {
  if (!isAdminOrSuperAdmin(req)) {
    const err = new Error("Only admin/superadmin can manage assignment rules.");
    err.statusCode = 403;
    throw err;
  }
};

const PRIORITIES = ["", "low", "medium", "high"];
const TEMPERATURES = ["", "cold", "warm", "hot"];
const STRATEGIES = ["round_robin", "least_loaded", "fixed_user"];

const getStartOfDay = (date = new Date()) => {
  const d = new Date(date);
  d.setHours(0, 0, 0, 0);
  return d;
};

const createNotificationSafe = async ({
  userId,
  title,
  message,
  type = "lead",
  priority = "normal",
  entityType = "Lead",
  entityId,
  createdBy,
}) => {
  try {
    if (!userId || !title) return null;

    return await Notification.create({
      userId,
      title,
      message,
      type,
      priority,
      entityType,
      entityId,
      createdBy,
    });
  } catch (err) {
    console.error("Notification failed:", err.message);
    return null;
  }
};

const createLeadQueueSafe = async ({ lead, assignedTo, createdBy }) => {
  try {
    if (!lead?._id || !assignedTo) return null;

    return await WorkQueue.findOneAndUpdate(
      {
        leadId: lead._id,
        assignedTo,
        source: "new_lead",
        status: { $in: ["pending", "in_progress", "snoozed"] },
      },
      {
        $set: {
          queueDate: getStartOfDay(new Date()),
          customerId: lead.customerId || null,
          title: lead.nextAction || "New lead needs first contact",
          description: `${lead.contact?.name || "Lead"} from ${
            lead.contact?.companyName || "company"
          }`,
          recommendedAction: lead.nextActionType === "call" ? "call" : "review",
          priority: lead.workQueuePriority || "normal",
          priorityScore: lead.workQueueScore || 0,
          dueAt: lead.nextActionAt || lead.nextFollowUpAt || new Date(),
          createdBy,
          autoGenerated: true,
        },
        $setOnInsert: {
          leadId: lead._id,
          assignedTo,
          status: "pending",
        },
      },
      { new: true, upsert: true, runValidators: true }
    );
  } catch (err) {
    console.error("Lead queue failed:", err.message);
    return null;
  }
};

const matchRuleForLead = async (lead) => {
  const rules = await LeadAssignmentRule.find({
    isActive: true,
  })
    .sort({ order: 1, createdAt: 1 })
    .lean();

  for (const rule of rules) {
    const sourceOk = !rule.source || rule.source === lead.source;
    const purchaseTypeOk = !rule.purchaseType || rule.purchaseType === lead.purchaseType;
    const priorityOk = !rule.priority || rule.priority === lead.priority;
    const tempOk = !rule.leadTemperature || rule.leadTemperature === lead.leadTemperature;

    if (sourceOk && purchaseTypeOk && priorityOk && tempOk) {
      return rule;
    }
  }

  return null;
};

const getTodayAssignedCount = async (userId) => {
  return Lead.countDocuments({
    assignedTo: userId,
    createdAt: { $gte: getStartOfDay(new Date()) },
  });
};

const chooseUserByRule = async (rule) => {
  const userIds = (rule.assignToUsers || []).filter(Boolean);
  if (!userIds.length) return null;

  const users = await User.find({
    _id: { $in: userIds },
    isActive: true,
    isAvailableForAssignment: true,
    workStatus: "available",
    role: "employee",
  })
    .select(
      "name email role dailyLeadLimit currentOpenLeadCount currentPendingWorkQueueCount lastAssignedLeadAt permissionGroup"
    )
    .populate("permissionGroup", "permissions isActive")
    .lean();

  const leadUsers = users.filter(
    (user) =>
      user.permissionGroup?.isActive !== false &&
      user.permissionGroup?.permissions?.includes?.("leads:view")
  );

  if (!leadUsers.length) return null;

  const eligible = [];

  for (const user of leadUsers) {
    if (Number(rule.maxDailyLeadsPerUser || 0) > 0) {
      const todayCount = await getTodayAssignedCount(user._id);
      if (todayCount >= Number(rule.maxDailyLeadsPerUser)) continue;
    }

    if (Number(user.dailyLeadLimit || 0) > 0) {
      const todayCount = await getTodayAssignedCount(user._id);
      if (todayCount >= Number(user.dailyLeadLimit)) continue;
    }

    eligible.push(user);
  }

  if (!eligible.length) return null;

  if (rule.strategy === "fixed_user") {
    return eligible[0];
  }

  if (rule.strategy === "least_loaded") {
    eligible.sort((a, b) => {
      const loadA =
        Number(a.currentOpenLeadCount || 0) +
        Number(a.currentPendingWorkQueueCount || 0);
      const loadB =
        Number(b.currentOpenLeadCount || 0) +
        Number(b.currentPendingWorkQueueCount || 0);

      return loadA - loadB;
    });

    return eligible[0];
  }

  if (rule.strategy === "round_robin") {
    const last = String(rule.lastAssignedUser || "");

    if (!last) return eligible[0];

    const index = eligible.findIndex((u) => String(u._id) === last);
    const nextIndex = index >= 0 ? (index + 1) % eligible.length : 0;

    return eligible[nextIndex];
  }

  return eligible[0];
};

/* =======================
   CREATE ASSIGNMENT RULE
======================= */
export const createAssignmentRule = async (req, res) => {
  try {
    assertAdmin(req);
    const meta = getReqMeta(req);

    const {
      name,
      description = "",
      source = "",
      purchaseType = "",
      priority = "",
      leadTemperature = "",
      assignToUsers = [],
      strategy = "least_loaded",
      maxDailyLeadsPerUser = 0,
      isActive = true,
      order = 100,
    } = req.body || {};

    if (!name || !normalizeString(name)) {
      return res.status(400).json({ message: "name is required" });
    }

    if (!PRIORITIES.includes(priority)) {
      return res.status(400).json({
        message: `Invalid priority. Use: ${PRIORITIES.join(", ")}`,
      });
    }

    if (!TEMPERATURES.includes(leadTemperature)) {
      return res.status(400).json({
        message: `Invalid leadTemperature. Use: ${TEMPERATURES.join(", ")}`,
      });
    }

    if (!STRATEGIES.includes(strategy)) {
      return res.status(400).json({
        message: `Invalid strategy. Use: ${STRATEGIES.join(", ")}`,
      });
    }

    const safeUsers = Array.isArray(assignToUsers)
      ? assignToUsers.map((id) => toObjectId(id)).filter(Boolean)
      : [];

    if (!safeUsers.length) {
      return res.status(400).json({
        message: "At least one assignToUsers is required",
      });
    }

    const rule = await LeadAssignmentRule.create({
      name: normalizeString(name),
      description: normalizeString(description),
      source: normalizeString(source),
      purchaseType: normalizeString(purchaseType),
      priority: normalizeLower(priority),
      leadTemperature: normalizeLower(leadTemperature),
      assignToUsers: safeUsers,
      strategy,
      maxDailyLeadsPerUser: Math.max(Number(maxDailyLeadsPerUser || 0), 0),
      isActive: Boolean(isActive),
      order: Number(order || 100),
      createdBy: req.user._id,
    });

    await writeAudit({
      actorId: req.user._id,
      action: "create",
      entityType: "LeadAssignmentRule",
      entityId: rule._id,
      before: null,
      after: rule.toObject(),
      meta,
    });

    return res.status(201).json({
      message: "Assignment rule created",
      rule,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to create assignment rule",
      error: err.message,
    });
  }
};

/* =======================
   LIST ASSIGNMENT RULES
======================= */
export const listAssignmentRules = async (req, res) => {
  try {
    assertAdmin(req);

    const { isActive, strategy, limit = 100 } = req.query || {};

    const filter = {};

    if (String(isActive).toLowerCase() === "true") filter.isActive = true;
    if (String(isActive).toLowerCase() === "false") filter.isActive = false;
    if (strategy && STRATEGIES.includes(String(strategy))) filter.strategy = strategy;

    const pageSize = Math.min(Math.max(parseInt(limit || "100", 10), 1), 200);

    const rules = await LeadAssignmentRule.find(filter)
      .populate("assignToUsers", "name email role avatarUrl workStatus isAvailableForAssignment")
      .populate("lastAssignedUser", "name email role avatarUrl")
      .populate("createdBy", "name email role avatarUrl")
      .sort({ isActive: -1, order: 1, createdAt: -1 })
      .limit(pageSize)
      .lean();

    return res.json({ rules });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to list assignment rules",
      error: err.message,
    });
  }
};

