/* =======================
   UPDATE ASSIGNMENT RULE
======================= */
export const updateAssignmentRule = async (req, res) => {
  try {
    assertAdmin(req);
    const meta = getReqMeta(req);

    const id = toObjectId(req.params.id);
    if (!id) return res.status(400).json({ message: "Invalid assignment rule id" });

    const before = await LeadAssignmentRule.findById(id).lean();
    if (!before) return res.status(404).json({ message: "Assignment rule not found" });

    const set = {};

    if (req.body?.name !== undefined) set.name = normalizeString(req.body.name);
    if (req.body?.description !== undefined) {
      set.description = normalizeString(req.body.description);
    }
    if (req.body?.source !== undefined) set.source = normalizeString(req.body.source);
    if (req.body?.purchaseType !== undefined) {
      set.purchaseType = normalizeString(req.body.purchaseType);
    }

    if (req.body?.priority !== undefined) {
      if (!PRIORITIES.includes(req.body.priority)) {
        return res.status(400).json({ message: "Invalid priority" });
      }
      set.priority = req.body.priority;
    }

    if (req.body?.leadTemperature !== undefined) {
      if (!TEMPERATURES.includes(req.body.leadTemperature)) {
        return res.status(400).json({ message: "Invalid leadTemperature" });
      }
      set.leadTemperature = req.body.leadTemperature;
    }

    if (req.body?.assignToUsers !== undefined) {
      const safeUsers = Array.isArray(req.body.assignToUsers)
        ? req.body.assignToUsers.map((uid) => toObjectId(uid)).filter(Boolean)
        : [];

      if (!safeUsers.length) {
        return res.status(400).json({
          message: "At least one assignToUsers is required",
        });
      }

      set.assignToUsers = safeUsers;
    }

    if (req.body?.strategy !== undefined) {
      if (!STRATEGIES.includes(req.body.strategy)) {
        return res.status(400).json({ message: "Invalid strategy" });
      }
      set.strategy = req.body.strategy;
    }

    if (req.body?.maxDailyLeadsPerUser !== undefined) {
      set.maxDailyLeadsPerUser = Math.max(
        Number(req.body.maxDailyLeadsPerUser || 0),
        0
      );
    }

    if (req.body?.isActive !== undefined) {
      set.isActive = Boolean(req.body.isActive);
    }

    if (req.body?.order !== undefined) {
      set.order = Number(req.body.order || 100);
    }

    if (!Object.keys(set).length) {
      return res.status(400).json({ message: "No valid fields provided." });
    }

    const rule = await LeadAssignmentRule.findByIdAndUpdate(
      id,
      { $set: set },
      { new: true, runValidators: true }
    );

    await writeAudit({
      actorId: req.user._id,
      action: "update",
      entityType: "LeadAssignmentRule",
      entityId: id,
      before,
      after: rule.toObject(),
      meta,
    });

    return res.json({
      message: "Assignment rule updated",
      rule,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to update assignment rule",
      error: err.message,
    });
  }
};

