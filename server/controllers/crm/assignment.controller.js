/* =======================
   AUTO ASSIGN SINGLE LEAD
======================= */
export const autoAssignLead = async (req, res) => {
  try {
    assertAdmin(req);
    const meta = getReqMeta(req);

    const { leadId } = req.body || {};
    const safeLeadId = toObjectId(leadId);

    if (!safeLeadId) {
      return res.status(400).json({ message: "Valid leadId is required" });
    }

    const lead = await Lead.findById(safeLeadId);
    if (!lead) return res.status(404).json({ message: "Lead not found" });

    const before = lead.toObject();

    const rule = await matchRuleForLead(lead);
    if (!rule) {
      return res.status(404).json({
        message: "No active assignment rule matched this lead.",
      });
    }

    const user = await chooseUserByRule(rule);
    if (!user) {
      return res.status(404).json({
        message: "No available user found for this assignment rule.",
      });
    }

    lead.assignedTo = user._id;
    lead.ownerLocked = false;
    await lead.save();

    await LeadAssignmentRule.findByIdAndUpdate(rule._id, {
      $set: { lastAssignedUser: user._id },
    });

    await User.findByIdAndUpdate(user._id, {
      $set: { lastAssignedLeadAt: new Date() },
      $inc: { currentOpenLeadCount: 1 },
    });

    await createLeadQueueSafe({
      lead,
      assignedTo: user._id,
      createdBy: req.user._id,
    });

    await createNotificationSafe({
      userId: user._id,
      title: "New lead assigned",
      message: `${lead.contact?.name || "Lead"} from ${
        lead.contact?.companyName || "company"
      }`,
      priority: lead.workQueuePriority || "normal",
      entityId: lead._id,
      createdBy: req.user._id,
    });

    await writeAudit({
      actorId: req.user._id,
      action: "auto_assign",
      entityType: "Lead",
      entityId: lead._id,
      before,
      after: lead.toObject(),
      meta,
    });

    await writeActivity({
      leadId: lead._id,
      entityType: "Lead",
      entityId: lead._id,
      type: "lead_assigned",
      message: `Lead auto-assigned to ${user.name}`,
      createdBy: req.user._id,
      meta: {
        assignedTo: user._id,
        ruleId: rule._id,
      },
    });

    return res.json({
      message: "Lead auto-assigned",
      lead,
      assignedTo: user,
      rule,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to auto assign lead",
      error: err.message,
    });
  }
};

/* =======================
   MANUAL ASSIGN LEAD
======================= */
export const manualAssignLead = async (req, res) => {
  try {
    if (!isAdminOrSuperAdmin(req)) {
      return res.status(403).json({
        message: "Only admin/superadmin can assign leads.",
      });
    }

    const meta = getReqMeta(req);

    const { leadId, assignedTo, lockOwner = false } = req.body || {};

    const safeLeadId = toObjectId(leadId);
    const safeAssignedTo = toObjectId(assignedTo);

    if (!safeLeadId) return res.status(400).json({ message: "Valid leadId is required" });
    if (!safeAssignedTo) return res.status(400).json({ message: "Valid assignedTo is required" });

    const lead = await Lead.findById(safeLeadId);
    if (!lead) return res.status(404).json({ message: "Lead not found" });

    const user = await User.findById(safeAssignedTo).select(
      "name email role isActive isAvailableForAssignment workStatus"
    );

    if (!user || !user.isActive) {
      return res.status(404).json({
        message: "Assigned user not found or inactive.",
      });
    }

    const before = lead.toObject();

    lead.assignedTo = safeAssignedTo;
    lead.ownerLocked = Boolean(lockOwner);

    await lead.save();

    await User.findByIdAndUpdate(safeAssignedTo, {
      $set: { lastAssignedLeadAt: new Date() },
      $inc: { currentOpenLeadCount: 1 },
    });

    await createLeadQueueSafe({
      lead,
      assignedTo: safeAssignedTo,
      createdBy: req.user._id,
    });

    await createNotificationSafe({
      userId: safeAssignedTo,
      title: "Lead assigned to you",
      message: `${lead.contact?.name || "Lead"} from ${
        lead.contact?.companyName || "company"
      }`,
      priority: lead.workQueuePriority || "normal",
      entityId: lead._id,
      createdBy: req.user._id,
    });

    await writeAudit({
      actorId: req.user._id,
      action: "assign",
      entityType: "Lead",
      entityId: lead._id,
      before,
      after: lead.toObject(),
      meta,
    });

    await writeActivity({
      leadId: lead._id,
      entityType: "Lead",
      entityId: lead._id,
      type: "lead_assigned",
      message: `Lead assigned to ${user.name}`,
      createdBy: req.user._id,
      meta: {
        assignedTo: user._id,
        lockOwner: Boolean(lockOwner),
      },
    });

    return res.json({
      message: "Lead assigned",
      lead,
      assignedTo: user,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to assign lead",
      error: err.message,
    });
  }
};

/* =======================
   AUTO ASSIGN UNASSIGNED / BULK
======================= */
export const autoAssignBulkLeads = async (req, res) => {
  try {
    assertAdmin(req);

    const { limit = 50 } = req.body || {};
    const pageSize = Math.min(Math.max(parseInt(limit || "50", 10), 1), 200);

    const leads = await Lead.find({
      pipelineStage: { $nin: ["won", "lost"] },
    })
      .sort({ createdAt: -1 })
      .limit(pageSize);

    const results = [];

    for (const lead of leads) {
      const rule = await matchRuleForLead(lead);
      if (!rule) {
        results.push({
          leadId: lead._id,
          success: false,
          reason: "No rule matched",
        });
        continue;
      }

      const user = await chooseUserByRule(rule);
      if (!user) {
        results.push({
          leadId: lead._id,
          success: false,
          reason: "No available user",
        });
        continue;
      }

      const beforeAssignedTo = lead.assignedTo;

      lead.assignedTo = user._id;
      lead.ownerLocked = false;
      await lead.save();

      await LeadAssignmentRule.findByIdAndUpdate(rule._id, {
        $set: { lastAssignedUser: user._id },
      });

      await User.findByIdAndUpdate(user._id, {
        $set: { lastAssignedLeadAt: new Date() },
        $inc: { currentOpenLeadCount: 1 },
      });

      await createLeadQueueSafe({
        lead,
        assignedTo: user._id,
        createdBy: req.user._id,
      });

      await createNotificationSafe({
        userId: user._id,
        title: "New lead assigned",
        message: `${lead.contact?.name || "Lead"} from ${
          lead.contact?.companyName || "company"
        }`,
        priority: lead.workQueuePriority || "normal",
        entityId: lead._id,
        createdBy: req.user._id,
      });

      await writeActivity({
        leadId: lead._id,
        entityType: "Lead",
        entityId: lead._id,
        type: "lead_assigned",
        message: `Lead auto-assigned to ${user.name}`,
        createdBy: req.user._id,
        meta: {
          oldAssignedTo: beforeAssignedTo,
          assignedTo: user._id,
          ruleId: rule._id,
        },
      });

      results.push({
        leadId: lead._id,
        success: true,
        assignedTo: user._id,
        ruleId: rule._id,
      });
    }

    return res.json({
      message: "Bulk auto assignment completed",
      results,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed bulk auto assignment",
      error: err.message,
    });
  }
};

/* =======================
   AVAILABLE ASSIGNEES
======================= */
export const listAvailableAssignees = async (req, res) => {
  try {
    if (!isAdminOrSuperAdmin(req)) {
      return res.status(403).json({
        message: "Only admin/superadmin can view available assignees.",
      });
    }

    const { q = "", role = "" } = req.query || {};

    const filter = {
      isActive: true,
      isAvailableForAssignment: true,
      workStatus: "available",
      role: "employee",
    };

    if (role && String(role) === "employee") {
      filter.role = role;
    }

    if (q && normalizeString(q)) {
      filter.nameLower = {
        $regex: normalizeString(q).toLowerCase(),
        $options: "i",
      };
    }

    const usersRaw = await User.find(filter)
      .select(
        "name email role avatarUrl teamRole dailyLeadLimit currentOpenLeadCount currentPendingWorkQueueCount workStatus lastAssignedLeadAt permissionGroup"
      )
      .populate("permissionGroup", "name permissions isActive")
      .sort({ currentOpenLeadCount: 1, lastAssignedLeadAt: 1 })
      .limit(100)
      .lean();

    const users = usersRaw.filter(
      (user) =>
        user.permissionGroup?.isActive !== false &&
        user.permissionGroup?.permissions?.includes?.("leads:view")
    );

    return res.json({ users });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to list available assignees",
      error: err.message,
    });
  }
};
