const toObjectId = (v) => {
  if (!v) return null;
  return mongoose.Types.ObjectId.isValid(v)
    ? new mongoose.Types.ObjectId(v)
    : null;
};

const normalizeString = (value = "") => String(value || "").trim();
const normalizeLower = (value = "") => normalizeString(value).toLowerCase();

const validateDateOrNull = (value) => {
  if (!value) return null;
  const dt = new Date(value);
  if (Number.isNaN(dt.getTime())) return null;
  return dt;
};

const isAdminOrSuperAdmin = (req) => {
  const role = req?.user?.role;
  const group = req?.user?.permissionGroup;
  return role === "admin" || role === "superadmin" || (group?.isActive !== false && group?.permissions?.includes?.("deals:manage"));
};

const assertLeadAccessOrThrow = async ({ req, leadId }) => {
  if (!leadId) return true;
  if (isAdminOrSuperAdmin(req)) return true;

  const me = new mongoose.Types.ObjectId(req.user._id);

  const exists = await Lead.exists({
    _id: leadId,
    $or: [
      { assignedTo: me },
      { allowedUsers: me },
      { createdBy: me, ownerLocked: false },
    ],
  });

  if (!exists) {
    const err = new Error("Not authorized to access this lead");
    err.statusCode = 403;
    throw err;
  }

  return true;
};

const DEAL_STAGES = ["new", "qualified", "proposal", "negotiation", "won", "lost"];
const DEAL_READY_PROPOSAL_STATUSES = ["sent", "accepted"];

const PROPOSAL_STATUSES = ["none", "draft", "sent", "accepted", "rejected", "expired"];

const calculateItems = (items = []) => {
  let subtotal = 0;
  let discountTotal = 0;

  const normalized = Array.isArray(items)
    ? items.map((item) => {
        const qty = Math.max(Number(item.qty || 0), 0);
        const unitPrice = Math.max(Number(item.unitPrice || 0), 0);
        const discount = Math.max(Number(item.discount || 0), 0);

        const rawTotal = qty * unitPrice;
        const lineTotal = Math.max(rawTotal - discount, 0);

        subtotal += rawTotal;
        discountTotal += discount;

        return {
          productId: toObjectId(item.productId),
          nameSnapshot: normalizeString(item.nameSnapshot),
          qty,
          unitPrice,
          discount,
          lineTotal,
        };
      })
    : [];

  return {
    items: normalized,
    subtotal,
    discountTotal,
    grandTotal: Math.max(subtotal - discountTotal, 0),
  };
};

const getExpectedRevenue = (grandTotal, probability) => {
  return Math.round(Number(grandTotal || 0) * (Number(probability || 0) / 100));
};

const getDealHealth = ({ stage, expectedCloseDate, lastActivityAt, probability }) => {
  if (stage === "won") return "healthy";
  if (stage === "lost") return "critical";

  const now = new Date();
  const closeDate = validateDateOrNull(expectedCloseDate);

  if (closeDate && closeDate < now) return "critical";

  if (!lastActivityAt) return "at_risk";

  const last = new Date(lastActivityAt);
  const daysSilent = Math.floor((now - last) / (24 * 60 * 60 * 1000));

  if (daysSilent >= 7) return "stuck";
  if (daysSilent >= 3) return "at_risk";

  if (Number(probability || 0) >= 70) return "healthy";

  return "unknown";
};

const getStartOfDay = (date = new Date()) => {
  const d = new Date(date);
  d.setHours(0, 0, 0, 0);
  return d;
};

const createOrUpdateDealQueue = async ({
  deal,
  lead = null,
  source = "manual",
  title = "Review deal",
  description = "",
  recommendedAction = "review",
  dueAt = null,
  priority = "normal",
  priorityScore = 70,
  createdBy,
}) => {
  try {
    const assignedTo = deal?.ownerId || lead?.assignedTo || deal?.createdBy;
    if (!deal?._id || !assignedTo) return null;

    return await WorkQueue.findOneAndUpdate(
      {
        dealId: deal._id,
        assignedTo,
        source,
        status: { $in: ["pending", "in_progress", "snoozed"] },
      },
      {
        $set: {
          queueDate: getStartOfDay(dueAt || new Date()),
          leadId: deal.leadId || null,
          customerId: deal.customerId || lead?.customerId || null,
          proposalId: deal.proposalId || null,
          title,
          description,
          recommendedAction,
          priority,
          priorityScore,
          dueAt,
          createdBy,
          autoGenerated: true,
        },
        $setOnInsert: {
          dealId: deal._id,
          assignedTo,
          status: "pending",
        },
      },
      { new: true, upsert: true, runValidators: true }
    );
  } catch (err) {
    console.error("Deal work queue failed:", err.message);
    return null;
  }
};

const createNotificationSafe = async ({
  userId,
  title,
  message,
  type = "deal",
  priority = "normal",
  entityType = "Deal",
  entityId,
  createdBy,
}) => {
  try {
    if (!userId || !title) return null;

    return await Notification.create({
      userId,
      title,
      message,
      type,
      priority,
      entityType,
      entityId,
      createdBy,
    });
  } catch (err) {
    console.error("Notification failed:", err.message);
    return null;
  }
};

const syncLeadForDeal = async ({ leadId, deal, action, userId }) => {
  if (!leadId) return null;

  const lead = await Lead.findById(leadId);
  if (!lead) return null;

  const set = {
    lastActivityAt: new Date(),
    untouchedSinceCreated: false,
  };

  let note = "Deal updated";
  let reason = "Deal updated";

  if (action === "created") {
    if (deal.stage === "won") {
      set.pipelineStage = "won";
      set.status = "confirmed";
      set.wonReason = deal.wonReason || "Deal won";
      set.wonAt = deal.wonAt || new Date();
      set.isOverdue = false;
      set.overdueSince = null;
      set.nextAction = "";
      set.nextActionType = "";
      set.nextActionAt = null;
      set.workQueuePriority = "high";
      set.workQueueScore = 120;
      note = `Deal created and won: ${deal.title}`;
      reason = deal.wonReason || "Deal won";
    } else {
      set.pipelineStage = "negotiation";
      set.status = lead.status === "new" ? "contacted" : lead.status;
      set.nextAction = "Negotiate terms and finalize sale";
      set.nextActionType = "follow_up";
      set.nextActionAt = deal.nextDealActionAt || deal.expectedCloseDate || null;
      set.workQueuePriority = "high";
      set.workQueueScore = Math.max(Number(lead.workQueueScore || 0), 95);
      note = `Deal created: ${deal.title}`;
      reason = "Deal created";
    }
  }

  if (action === "won") {
    set.pipelineStage = "won";
    set.status = "confirmed";
    set.wonReason = deal.wonReason || "Deal won";
    set.wonAt = deal.wonAt || new Date();
    set.isOverdue = false;
    set.overdueSince = null;
    set.nextAction = "";
    set.nextActionType = "";
    set.nextActionAt = null;
    set.workQueuePriority = "high";
    set.workQueueScore = 120;

    note = `Deal won: ${deal.title}`;
    reason = deal.wonReason || "Deal won";
  }

  if (action === "lost") {
    set.pipelineStage = "lost";
    set.status = "lost";
    set.lostReason = deal.lostReason || "Deal lost";
    set.lostAt = deal.lostAt || new Date();
    set.isOverdue = false;
    set.overdueSince = null;
    set.nextAction = "Review lost deal reason";
    set.nextActionType = "lost_review";
    set.nextActionAt = null;
    set.workQueuePriority = "low";
    set.workQueueScore = 0;

    note = `Deal lost: ${deal.title}`;
    reason = deal.lostReason || "Deal lost";
  }

  return await Lead.findByIdAndUpdate(
    leadId,
    {
      $set: set,
      $push: {
        notes: {
          note,
          type:
            action === "won"
              ? "won_reason"
              : action === "lost"
              ? "lost_reason"
              : "stage_change",
          oldStage: lead.pipelineStage || "",
          newStage: set.pipelineStage || lead.pipelineStage || "",
          oldStatus: lead.status || "",
          newStatus: set.status || lead.status || "",
          reason,
          createdBy: userId,
          createdAt: new Date(),
        },
      },
    },
    { new: true, runValidators: true }
  );
};

const convertWonDealLeadToCustomer = async ({ deal, userId }) => {
  if (!deal?.leadId) return { customer: null, lead: null };

  const lead = await Lead.findById(deal.leadId);
  if (!lead) return { customer: null, lead: null };

  let customer = null;
  const existingCustomerId = lead.customerId || lead.convertedCustomer || deal.customerId;

  if (existingCustomerId) customer = await Customer.findById(existingCustomerId);
  if (!customer) customer = await Customer.findOne({ leadId: lead._id });

  if (!customer) {
    customer = await Customer.create({
      name: lead.contact?.name || lead.contact?.companyName || "Customer",
      email: lead.contact?.email || "",
      phone: lead.contact?.phone || "",
      companyName: lead.contact?.companyName || "",
      contactPerson: {
        name: lead.contact?.name || lead.contact?.companyName || "Customer",
        email: lead.contact?.email || "",
        phone: lead.contact?.phone || "",
      },
      origin: "lead",
      lifecycleStage: "active",
      tags: lead.tags || [],
      createdBy: userId,
      assignedTo: lead.assignedTo ? [lead.assignedTo] : [userId],
      leadId: lead._id,
    });
  }

  const updatedLead = await Lead.findByIdAndUpdate(
    lead._id,
    {
      $set: {
        customerId: customer._id,
        convertedCustomer: customer._id,
        convertedAt: lead.convertedAt || new Date(),
        pipelineStage: "won",
        status: "confirmed",
        isOverdue: false,
        overdueSince: null,
        nextAction: "",
        nextActionType: "",
        nextActionAt: null,
        workQueueScore: 0,
        workQueuePriority: "low",
      },
    },
    { new: true, runValidators: true }
  );

  await Promise.all([
    Deal.findByIdAndUpdate(deal._id, { $set: { customerId: customer._id } }),
    deal.proposalId
      ? Proposal.findByIdAndUpdate(deal.proposalId, {
          $set: { customerId: customer._id, dealId: deal._id },
        })
      : Promise.resolve(),
  ]);

  return { customer, lead: updatedLead };
};

