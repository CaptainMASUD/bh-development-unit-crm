/* =======================
   UPDATE DEAL
======================= */
export const updateDeal = async (req, res) => {
  try {
    const meta = getReqMeta(req);

    const id = toObjectId(req.params.id);
    if (!id) return res.status(400).json({ message: "Invalid deal id" });

    const before = await Deal.findById(id).lean();
    if (!before) return res.status(404).json({ message: "Deal not found" });

    if (before.leadId) {
      await assertLeadAccessOrThrow({ req, leadId: before.leadId });
    }

    const set = {};

    if (req.body?.title !== undefined) set.title = normalizeString(req.body.title);

    if (before.leadId && req.body?.stage !== undefined && req.body.stage !== before.stage) return res.status(409).json({ message: "Lead deal outcomes are controlled by lead conversion." });
    if (req.body?.stage !== undefined) {
      if (!DEAL_STAGES.includes(String(req.body.stage))) {
        return res.status(400).json({
          message: `Invalid stage. Use: ${DEAL_STAGES.join(", ")}`,
        });
      }

      set.stage = req.body.stage;
      set.lastStageChangedAt = new Date();
    }

    if (req.body?.currency !== undefined) {
      set.currency = normalizeString(req.body.currency) || "BDT";
    }

    if (req.body?.probability !== undefined) {
      set.probability = Math.min(Math.max(Number(req.body.probability || 0), 0), 100);
    }

    if (req.body?.expectedCloseDate !== undefined) {
      set.expectedCloseDate = validateDateOrNull(req.body.expectedCloseDate);
    }

    if (req.body?.proposalStatus !== undefined) {
      if (!PROPOSAL_STATUSES.includes(String(req.body.proposalStatus))) {
        return res.status(400).json({
          message: `Invalid proposalStatus. Use: ${PROPOSAL_STATUSES.join(", ")}`,
        });
      }

      set.proposalStatus = req.body.proposalStatus;
    }

    if (req.body?.proposalSentAt !== undefined) {
      set.proposalSentAt = validateDateOrNull(req.body.proposalSentAt);
    }

    if (req.body?.quotationValidTill !== undefined) {
      set.quotationValidTill = validateDateOrNull(req.body.quotationValidTill);
    }

    if (req.body?.nextDealAction !== undefined) {
      set.nextDealAction = normalizeString(req.body.nextDealAction);
    }

    if (req.body?.nextDealActionAt !== undefined) {
      set.nextDealActionAt = validateDateOrNull(req.body.nextDealActionAt);
    }

    if (req.body?.stuckReason !== undefined) {
      set.stuckReason = normalizeString(req.body.stuckReason);
    }

    if (req.body?.dealHealth !== undefined) {
      set.dealHealth = req.body.dealHealth;
    }

    if (req.body?.notes !== undefined) {
      set.notes = normalizeString(req.body.notes);
    }

    if (req.body?.ownerId !== undefined) {
      set.ownerId = toObjectId(req.body.ownerId) || before.ownerId;
    }

    if (req.body?.items !== undefined) {
      const totals = calculateItems(req.body.items);
      set.items = totals.items;
      set.subtotal = totals.subtotal;
      set.discountTotal = totals.discountTotal;
      set.grandTotal = totals.grandTotal;
    }

    const nextGrandTotal =
      set.grandTotal !== undefined ? set.grandTotal : before.grandTotal;
    const nextProbability =
      set.probability !== undefined ? set.probability : before.probability;
    const nextStage = set.stage || before.stage;
    const nextExpectedCloseDate =
      set.expectedCloseDate !== undefined
        ? set.expectedCloseDate
        : before.expectedCloseDate;

    set.expectedRevenue = getExpectedRevenue(nextGrandTotal, nextProbability);

    if (!set.dealHealth) {
      set.dealHealth = getDealHealth({
        stage: nextStage,
        expectedCloseDate: nextExpectedCloseDate,
        lastActivityAt: before.lastActivityAt,
        probability: nextProbability,
      });
    }

    if (!Object.keys(set).length) {
      return res.status(400).json({ message: "No valid fields provided." });
    }

    const deal = await Deal.findByIdAndUpdate(
      id,
      { $set: set },
      { new: true, runValidators: true }
    );

    let updatedLead = null;

    if (deal.leadId && set.stage) {
      updatedLead = await syncLeadForDeal({
        leadId: deal.leadId,
        deal,
        action: deal.stage === "won" ? "won" : deal.stage === "lost" ? "lost" : "created",
        userId: req.user._id,
      });
    }

    await createOrUpdateDealQueue({
      deal,
      lead: updatedLead,
      source: deal.dealHealth === "stuck" ? "deal_stuck" : "manual",
      title: deal.nextDealAction || "Review deal",
      description: deal.stuckReason || deal.title,
      recommendedAction: "review",
      priority:
        deal.dealHealth === "critical"
          ? "urgent"
          : deal.dealHealth === "stuck"
          ? "high"
          : "normal",
      priorityScore:
        deal.dealHealth === "critical"
          ? 130
          : deal.dealHealth === "stuck"
          ? 100
          : 70,
      dueAt: deal.nextDealActionAt || deal.expectedCloseDate || new Date(),
      createdBy: req.user._id,
    });

    await writeAudit({
      actorId: req.user._id,
      action: "update",
      entityType: "Deal",
      entityId: id,
      before,
      after: deal.toObject(),
      meta,
    });

    if (deal.leadId) {
      await writeActivity({
        leadId: deal.leadId,
        customerId: deal.customerId,
        dealId: deal._id,
        proposalId: deal.proposalId,
        entityType: "Deal",
        entityId: deal._id,
        type:
          deal.stage === "won"
            ? "deal_won"
            : deal.stage === "lost"
            ? "deal_lost"
            : "updated",
        message: `Deal updated: ${deal.title}`,
        createdBy: req.user._id,
        meta: { fields: Object.keys(set), stage: deal.stage },
      });
    }

    return res.json({
      message: "Deal updated",
      deal,
      lead: updatedLead,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to update deal",
      error: err.message,
    });
  }
};

