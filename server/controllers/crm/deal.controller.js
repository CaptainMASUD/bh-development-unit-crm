export const createDeal = async (req, res) => {
  try {
    const meta = getReqMeta(req);

    const {
      leadId,
      customerId = null,
      proposalId = null,
      title,
      stage = "negotiation",
      currency = "BDT",
      items = [],
      probability = 10,
      expectedCloseDate = null,
      proposalStatus = "none",
      proposalSentAt = null,
      quotationValidTill = null,
      requirementSnapshot = {},
      ownerId = null,
      notes = "",
      nextDealAction = "",
      nextDealActionAt = null,
      stuckReason = "",
    } = req.body || {};

    const safeLeadId = toObjectId(leadId);
    let safeCustomerId = toObjectId(customerId);
    let safeProposalId = toObjectId(proposalId);

    if (safeLeadId) {
      await assertLeadAccessOrThrow({ req, leadId: safeLeadId });
      const sourceLead = await Lead.findById(safeLeadId).lean();
      if (!sourceLead) return res.status(404).json({ message: "Lead not found" });
      return res.status(409).json({ message: "Deals linked to leads are created automatically when the lead is won in Negotiation." });
    }

    if (!safeLeadId && !safeCustomerId) {
      return res.status(400).json({
        message: "Deal must be linked to a lead or a customer.",
      });
    }

    let sourceProposal = null;
    if (safeProposalId) {
      sourceProposal = await Proposal.findOne({
        _id: safeProposalId,
        ...(safeLeadId ? { leadId: safeLeadId } : {}),
      }).lean();
    } else if (safeLeadId) {
      sourceProposal = await Proposal.findOne({
        leadId: safeLeadId,
        status: { $in: DEAL_READY_PROPOSAL_STATUSES },
        dealId: null,
      })
        .sort({ acceptedAt: -1, sentAt: -1, createdAt: -1 })
        .lean();
      safeProposalId = sourceProposal?._id || null;
    }

    if (sourceProposal?.leadId && !safeLeadId) return res.status(409).json({ message: "Win the proposal lead in Negotiation; conversion creates the deal automatically." });
    if (sourceProposal) {
      const existingDeal = await Deal.findOne({ proposalId: sourceProposal._id }).lean();
      if (existingDeal) {
        return res.status(409).json({
          message: "A deal already exists for this proposal.",
          deal: existingDeal,
        });
      }
    }

    if (!title || !normalizeString(title)) {
      return res.status(400).json({ message: "title is required" });
    }

    const allowedDealStages = ["new", "qualified", "proposal", "negotiation", "won", "lost"];
    const dealStage = stage && allowedDealStages.includes(stage) ? stage : "negotiation";

    if (proposalStatus && !PROPOSAL_STATUSES.includes(proposalStatus)) {
      return res.status(400).json({
        message: `Invalid proposalStatus. Use: ${PROPOSAL_STATUSES.join(", ")}`,
      });
    }

    const totals = calculateItems(
      Array.isArray(items) && items.length ? items : sourceProposal?.items || []
    );
    const safeProbability =
      dealStage === "won"
        ? 100
        : dealStage === "lost"
        ? 0
        : Math.min(Math.max(Number(probability || 10), 0), 100);
    const safeExpectedCloseDate = validateDateOrNull(expectedCloseDate);
    const safeNextDealActionAt = validateDateOrNull(nextDealActionAt);
    const grandTotal = totals.grandTotal;

    const health = getDealHealth({
      stage: dealStage,
      expectedCloseDate: safeExpectedCloseDate,
      lastActivityAt: new Date(),
      probability: safeProbability,
    });

    const deal = await Deal.create({
      leadId: safeLeadId,
      customerId: safeCustomerId,
      proposalId: safeProposalId,
      title: normalizeString(title),
      stage: dealStage,
      currency: normalizeString(currency) || "BDT",
      items: totals.items,
      subtotal: totals.subtotal,
      discountTotal: totals.discountTotal,
      grandTotal,
      expectedRevenue: getExpectedRevenue(grandTotal, safeProbability),
      probability: safeProbability,
      expectedCloseDate: safeExpectedCloseDate,
      proposalStatus:
        sourceProposal?.status ||
        (PROPOSAL_STATUSES.includes(proposalStatus) ? proposalStatus : "none"),
      proposalSentAt: sourceProposal?.sentAt || validateDateOrNull(proposalSentAt),
      quotationValidTill:
        sourceProposal?.validTill || validateDateOrNull(quotationValidTill),
      requirementSnapshot: {
        summary: normalizeString(requirementSnapshot?.summary),
        budgetMin: Math.max(Number(requirementSnapshot?.budgetMin || 0), 0),
        budgetMax: Math.max(Number(requirementSnapshot?.budgetMax || 0), 0),
        expectedValue: Math.max(Number(requirementSnapshot?.expectedValue || 0), 0),
        timeline: normalizeString(requirementSnapshot?.timeline),
        decisionMaker: normalizeString(requirementSnapshot?.decisionMaker),
      },
      ownerId: toObjectId(ownerId) || req.user._id,
      createdBy: req.user._id,
      notes: normalizeString(notes) || normalizeString(sourceProposal.notes),

      dealHealth: health,
      nextDealAction: normalizeString(nextDealAction) || "Negotiate with the client",
      nextDealActionAt: safeNextDealActionAt || safeExpectedCloseDate,
      stuckReason: normalizeString(stuckReason),
      lastActivityAt: new Date(),
      lastStageChangedAt: new Date(),
    });

    let updatedLead = null;

    if (safeLeadId) {
      updatedLead = await syncLeadForDeal({
        leadId: safeLeadId,
        deal,
        action: "created",
        userId: req.user._id,
      });

      await writeActivity({
        leadId: safeLeadId,
        customerId: safeCustomerId,
        dealId: deal._id,
        proposalId: safeProposalId,
        entityType: "Deal",
        entityId: deal._id,
        type: "deal_created",
        message: "Deal created",
        createdBy: req.user._id,
        meta: {
          dealId: deal._id,
          amount: deal.grandTotal,
          stage: deal.stage,
        },
      });
    }

    if (safeProposalId) {
      await Proposal.findByIdAndUpdate(safeProposalId, {
        $set: { dealId: deal._id },
      });
    }

    await createOrUpdateDealQueue({
      deal,
      lead: updatedLead,
      source: "manual",
      title: deal.nextDealAction || "Work on deal",
      description: deal.title,
      recommendedAction: "review",
      priority: deal.dealHealth === "critical" ? "urgent" : "high",
      priorityScore: deal.dealHealth === "critical" ? 130 : 90,
      dueAt: deal.nextDealActionAt || deal.expectedCloseDate || new Date(),
      createdBy: req.user._id,
    });

    await createNotificationSafe({
      userId: deal.ownerId,
      title: "New deal created",
      message: deal.title,
      priority: deal.dealHealth === "critical" ? "urgent" : "high",
      entityId: deal._id,
      createdBy: req.user._id,
    });

    await writeAudit({
      actorId: req.user._id,
      action: "create",
      entityType: "Deal",
      entityId: deal._id,
      before: null,
      after: deal.toObject(),
      meta,
    });

    return res.status(201).json({
      message: "Deal created",
      deal,
      lead: updatedLead,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to create deal",
      error: err.message,
    });
  }
};

