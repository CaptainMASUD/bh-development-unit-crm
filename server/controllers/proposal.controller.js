/* =======================
   UPDATE PROPOSAL
======================= */
export const updateProposal = async (req, res) => {
  try {
    const meta = getReqMeta(req);

    const id = toObjectId(req.params.id);
    if (!id) return res.status(400).json({ message: "Invalid proposal id" });

    const before = await Proposal.findById(id).lean();
    if (!before) return res.status(404).json({ message: "Proposal not found" });

    if (before.leadId) {
      await assertLeadAccessOrThrow({ req, leadId: before.leadId });
    }

    if (!["draft", "sent"].includes(before.status)) {
      return res.status(400).json({
        message: "Only draft or sent proposals can be edited.",
      });
    }

    const set = {};

    if (req.body?.title !== undefined) set.title = normalizeString(req.body.title);
    if (req.body?.currency !== undefined) {
      set.currency = normalizeString(req.body.currency) || "BDT";
    }
    if (req.body?.validTill !== undefined) {
      set.validTill = validateDateOrNull(req.body.validTill);
    }
    if (req.body?.terms !== undefined) set.terms = normalizeString(req.body.terms);
    if (req.body?.notes !== undefined) set.notes = normalizeString(req.body.notes);
    if (req.body?.ownerId !== undefined) {
      set.ownerId = toObjectId(req.body.ownerId) || before.ownerId;
    }
    if (req.body?.followupDueAt !== undefined) {
      set.followupDueAt = validateDateOrNull(req.body.followupDueAt);
    }
    if (req.body?.lastClientResponse !== undefined) {
      set.lastClientResponse = normalizeString(req.body.lastClientResponse);
      set.lastClientResponseAt = new Date();
    }

    if (req.body?.items !== undefined) {
      const totals = calculateItems(req.body.items);
      set.items = totals.items;
      set.subtotal = totals.subtotal;
      set.discountTotal = totals.discountTotal;
      set.grandTotal = totals.grandTotal;
    }

    if (!Object.keys(set).length) {
      return res.status(400).json({ message: "No valid fields provided." });
    }

    const proposal = await Proposal.findByIdAndUpdate(
      id,
      { $set: set },
      { new: true, runValidators: true }
    );

    await writeAudit({
      actorId: req.user._id,
      action: "update",
      entityType: "Proposal",
      entityId: id,
      before,
      after: proposal.toObject(),
      meta,
    });

    if (proposal.leadId) {
      await writeActivity({
        leadId: proposal.leadId,
        customerId: proposal.customerId,
        dealId: proposal.dealId,
        proposalId: proposal._id,
        entityType: "Proposal",
        entityId: proposal._id,
        type: "updated",
        message: "Proposal updated",
        createdBy: req.user._id,
        meta: { fields: Object.keys(set) },
      });
    }

    return res.json({
      message: "Proposal updated",
      proposal,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to update proposal",
      error: err.message,
    });
  }
};

