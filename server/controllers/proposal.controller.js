const toObjectId = (v) => {
  if (!v) return null;
  return mongoose.Types.ObjectId.isValid(v)
    ? new mongoose.Types.ObjectId(v)
    : null;
};

const normalizeString = (value = "") => String(value || "").trim();

const validateDateOrNull = (value) => {
  if (!value) return null;
  const dt = new Date(value);
  if (Number.isNaN(dt.getTime())) return null;
  return dt;
};

const isAdminOrSuperAdmin = (req) => {
  const role = req?.user?.role;
  return role === "admin" || role === "superadmin";
};

const assertLeadAccessOrThrow = async ({ req, leadId }) => {
  if (!leadId) return true;
  if (isAdminOrSuperAdmin(req)) return true;

  const me = new mongoose.Types.ObjectId(req.user._id);

  const exists = await Lead.exists({
    _id: leadId,
    $or: [
      { assignedTo: me },
      { allowedUsers: me },
      { createdBy: me, ownerLocked: false },
    ],
  });

  if (!exists) {
    const err = new Error("Not authorized to access this lead");
    err.statusCode = 403;
    throw err;
  }

  return true;
};

const PROPOSAL_STATUSES = [
  "draft",
  "sent",
  "accepted",
  "rejected",
  "expired",
  "cancelled",
];

const calculateItems = (items = []) => {
  let subtotal = 0;
  let discountTotal = 0;

  const normalized = Array.isArray(items)
    ? items.map((item) => {
        const qty = Math.max(Number(item.qty || 0), 0);
        const unitPrice = Math.max(Number(item.unitPrice || 0), 0);
        const discount = Math.max(Number(item.discount || 0), 0);

        const rawTotal = qty * unitPrice;
        const lineTotal = Math.max(rawTotal - discount, 0);

        subtotal += rawTotal;
        discountTotal += discount;

        return {
          productId: toObjectId(item.productId),
          nameSnapshot: normalizeString(item.nameSnapshot),
          description: normalizeString(item.description),
          qty,
          unitPrice,
          discount,
          lineTotal,
        };
      })
    : [];

  return {
    items: normalized,
    subtotal,
    discountTotal,
    grandTotal: Math.max(subtotal - discountTotal, 0),
  };
};

const getStartOfDay = (date = new Date()) => {
  const d = new Date(date);
  d.setHours(0, 0, 0, 0);
  return d;
};

const createOrUpdateProposalQueue = async ({
  proposal,
  lead = null,
  source = "proposal_follow_up",
  title = "Follow up proposal",
  description = "",
  dueAt = null,
  priority = "high",
  priorityScore = 100,
  createdBy,
}) => {
  try {
    const assignedTo = lead?.assignedTo || proposal?.ownerId || proposal?.createdBy;
    if (!proposal?._id || !assignedTo) return null;

    return await WorkQueue.findOneAndUpdate(
      {
        proposalId: proposal._id,
        assignedTo,
        source,
        status: { $in: ["pending", "in_progress", "snoozed"] },
      },
      {
        $set: {
          queueDate: getStartOfDay(dueAt || new Date()),
          leadId: proposal.leadId || null,
          customerId: proposal.customerId || lead?.customerId || null,
          dealId: proposal.dealId || null,
          title,
          description,
          recommendedAction: "follow_up",
          priority,
          priorityScore,
          dueAt,
          createdBy,
          autoGenerated: true,
        },
        $setOnInsert: {
          proposalId: proposal._id,
          assignedTo,
          status: "pending",
        },
      },
      { new: true, upsert: true, runValidators: true }
    );
  } catch (err) {
    console.error("Proposal work queue failed:", err.message);
    return null;
  }
};

const createNotificationSafe = async ({
  userId,
  title,
  message,
  type = "proposal",
  priority = "normal",
  entityType = "Proposal",
  entityId,
  createdBy,
}) => {
  try {
    if (!userId || !title) return null;

    return await Notification.create({
      userId,
      title,
      message,
      type,
      priority,
      entityType,
      entityId,
      createdBy,
    });
  } catch (err) {
    console.error("Notification failed:", err.message);
    return null;
  }
};

const syncLeadForProposal = async ({ leadId, proposal, action, userId }) => {
  if (!leadId) return null;

  const lead = await Lead.findById(leadId);
  if (!lead) return null;

  const set = {
    lastActivityAt: new Date(),
    untouchedSinceCreated: false,
  };

  let noteType = "general";
  let note = "Proposal updated";
  let reason = "Proposal updated";

  if (action === "created") {
    set.nextAction = "Send proposal to client";
    set.nextActionType = "proposal";
    set.nextActionAt = proposal.validTill || null;
    set.workQueuePriority = "high";
    set.workQueueScore = Math.max(Number(lead.workQueueScore || 0), 90);
    noteType = "stage_change";
    note = `Proposal created: ${proposal.title}`;
    reason = "Proposal created";
  }

  if (action === "sent") {
    set.nextAction = "Follow up about proposal";
    set.nextActionType = "follow_up";
    set.nextActionAt = proposal.followupDueAt || null;
    set.nextFollowUpAt = proposal.followupDueAt || lead.nextFollowUpAt;
    set.workQueuePriority = "high";
    set.workQueueScore = Math.max(Number(lead.workQueueScore || 0), 100);
    noteType = "stage_change";
    note = `Proposal sent: ${proposal.title}`;
    reason = "Proposal sent";
  }

  if (action === "accepted") {
    set.status = lead.status === "new" ? "contacted" : lead.status;
    set.nextAction = "Create deal from accepted proposal";
    set.nextActionType = "deal";
    set.nextActionAt = null;
    set.workQueuePriority = "urgent";
    set.workQueueScore = 130;
    noteType = "stage_change";
    note = `Proposal accepted: ${proposal.title}`;
    reason = "Proposal accepted";
  }

  if (action === "rejected") {
    set.nextAction = "Review rejected proposal";
    set.nextActionType = "follow_up";
    set.workQueuePriority = "normal";
    set.workQueueScore = Math.max(Number(lead.workQueueScore || 0), 50);
    noteType = "general";
    note = `Proposal rejected: ${proposal.title}`;
    reason = proposal.rejectReason || "Proposal rejected";
  }

  return await Lead.findByIdAndUpdate(
    leadId,
    {
      $set: set,
      $push: {
        notes: {
          note,
          type: noteType,
          oldStage: lead.pipelineStage || "",
          newStage: set.pipelineStage || lead.pipelineStage || "",
          oldStatus: lead.status || "",
          newStatus: set.status || lead.status || "",
          reason,
          createdBy: userId,
          createdAt: new Date(),
        },
      },
    },
    { new: true, runValidators: true }
  );
};

/* =======================
   CREATE PROPOSAL
======================= */
export const createProposal = async (req, res) => {
  try {
    const meta = getReqMeta(req);

    const {
      leadId,
      customerId = null,
      dealId = null,
      title,
      currency = "BDT",
      items = [],
      validTill = null,
      terms = "",
      notes = "",
      ownerId = null,
    } = req.body || {};

    const safeLeadId = toObjectId(leadId);
    const safeCustomerId = toObjectId(customerId);
    const safeDealId = toObjectId(dealId);

    if (!safeLeadId && !safeCustomerId && !safeDealId) {
      return res.status(400).json({
        message: "Proposal must be connected to lead, customer, or deal.",
      });
    }

    if (safeLeadId) await assertLeadAccessOrThrow({ req, leadId: safeLeadId });

    if (!title || !normalizeString(title)) {
      return res.status(400).json({ message: "title is required" });
    }

    const totals = calculateItems(items);

    const proposal = await Proposal.create({
      leadId: safeLeadId,
      customerId: safeCustomerId,
      dealId: safeDealId,
      title: normalizeString(title),
      status: "draft",
      currency: normalizeString(currency) || "BDT",
      items: totals.items,
      subtotal: totals.subtotal,
      discountTotal: totals.discountTotal,
      grandTotal: totals.grandTotal,
      validTill: validateDateOrNull(validTill),
      terms: normalizeString(terms),
      notes: normalizeString(notes),
      createdBy: req.user._id,
      ownerId: toObjectId(ownerId) || req.user._id,
    });

    let updatedLead = null;

    if (safeLeadId) {
      updatedLead = await syncLeadForProposal({
        leadId: safeLeadId,
        proposal,
        action: "created",
        userId: req.user._id,
      });

      await createOrUpdateProposalQueue({
        proposal,
        lead: updatedLead,
        source: "manual",
        title: "Send proposal to client",
        description: proposal.title,
        dueAt: proposal.validTill || new Date(),
        priority: "high",
        priorityScore: 90,
        createdBy: req.user._id,
      });

      await writeActivity({
        leadId: safeLeadId,
        customerId: safeCustomerId,
        dealId: safeDealId,
        proposalId: proposal._id,
        entityType: "Proposal",
        entityId: proposal._id,
        type: "proposal_created",
        message: "Proposal created",
        createdBy: req.user._id,
        meta: {
          proposalId: proposal._id,
          amount: proposal.grandTotal,
        },
      });
    }

    await writeAudit({
      actorId: req.user._id,
      action: "create",
      entityType: "Proposal",
      entityId: proposal._id,
      before: null,
      after: proposal.toObject(),
      meta,
    });

    return res.status(201).json({
      message: "Proposal created",
      proposal,
      lead: updatedLead,
    });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to create proposal",
      error: err.message,
    });
  }
};

/* =======================
   LIST PROPOSALS
======================= */
export const listProposals = async (req, res) => {
  try {
    const { leadId, customerId, dealId, status, q, limit = 50 } = req.query || {};

    const filter = {};

    const safeLeadId = toObjectId(leadId);
    if (safeLeadId) {
      await assertLeadAccessOrThrow({ req, leadId: safeLeadId });
      filter.leadId = safeLeadId;
    }

    const safeCustomerId = toObjectId(customerId);
    if (safeCustomerId) filter.customerId = safeCustomerId;

    const safeDealId = toObjectId(dealId);
    if (safeDealId) filter.dealId = safeDealId;

    if (status && PROPOSAL_STATUSES.includes(String(status))) {
      filter.status = status;
    }

    const pageSize = Math.min(Math.max(parseInt(limit || "50", 10), 1), 100);

    let query = Proposal.find(filter)
      .populate("createdBy", "name email role avatarUrl")
      .populate("ownerId", "name email role avatarUrl");

    if (q && normalizeString(q)) {
      query = query
        .find({ ...filter, $text: { $search: normalizeString(q) } })
        .select({ score: { $meta: "textScore" } })
        .sort({ score: { $meta: "textScore" }, _id: -1 });
    } else {
      query = query.sort({ createdAt: -1 });
    }

    const items = await query.limit(pageSize).lean();

    return res.json({ items });
  } catch (err) {
    const code = err.statusCode || 500;

    return res.status(code).json({
      message: err.statusCode ? err.message : "Failed to list proposals",
      error: err.message,
    });
  }
};

